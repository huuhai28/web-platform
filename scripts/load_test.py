#!/usr/bin/env python3
"""Async load test using unique Keycloak users and realistic API flows."""

from __future__ import annotations

import argparse
import asyncio
import getpass
import math
import os
import random
import statistics
import sys
import time
from collections import defaultdict
from dataclasses import dataclass

import httpx


@dataclass
class Sample:
    endpoint: str
    elapsed_ms: float
    ok: bool
    status: int
    error: str = ""


def secret_from_env(name: str, prompt: str) -> str:
    value = os.getenv(name)
    if value:
        return value
    if sys.stdin.isatty():
        return getpass.getpass(prompt)
    raise SystemExit(f"Missing environment variable: {name}")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Run a controlled load test against Personal Web Platform."
    )
    parser.add_argument("--base-url", default="http://localhost:3000")
    parser.add_argument("--realm", default="personal-web")
    parser.add_argument("--client-id", default="load-test-client")
    parser.add_argument("--users", type=int, default=1000)
    parser.add_argument("--prefix", default="loaduser")
    parser.add_argument("--start-index", type=int, default=1)
    parser.add_argument("--concurrency", type=int, default=50)
    parser.add_argument("--ramp-up", type=float, default=60.0)
    parser.add_argument("--iterations", type=int, default=1)
    parser.add_argument(
        "--contact-rate",
        type=float,
        default=0.01,
        help="Fraction of users that POST contact data; 0 disables writes.",
    )
    parser.add_argument("--timeout", type=float, default=15.0)
    parser.add_argument("--max-error-rate", type=float, default=0.01)
    parser.add_argument("--max-p95-ms", type=float, default=1500.0)
    parser.add_argument(
        "--confirm-target",
        required=True,
        help="Must exactly match --base-url to prevent accidental load tests.",
    )
    return parser.parse_args()


async def measured_request(
    client: httpx.AsyncClient,
    samples: list[Sample],
    endpoint: str,
    method: str,
    path: str,
    expected: int,
    **kwargs,
) -> httpx.Response | None:
    started = time.perf_counter()
    try:
        response = await client.request(method, path, **kwargs)
        elapsed = (time.perf_counter() - started) * 1000
        ok = response.status_code == expected
        samples.append(
            Sample(endpoint, elapsed, ok, response.status_code, "" if ok else response.text[:160])
        )
        return response if ok else None
    except Exception as exc:
        elapsed = (time.perf_counter() - started) * 1000
        samples.append(Sample(endpoint, elapsed, False, 0, str(exc)))
        return None


async def virtual_user(
    number: int,
    args: argparse.Namespace,
    password: str,
    client: httpx.AsyncClient,
    semaphore: asyncio.Semaphore,
    samples: list[Sample],
) -> None:
    if args.ramp_up > 0 and args.users > 1:
        await asyncio.sleep((number - 1) * args.ramp_up / (args.users - 1))
    username = f"{args.prefix}{args.start_index + number - 1:04d}"
    async with semaphore:
        token_response = await measured_request(
            client,
            samples,
            "keycloak_token",
            "POST",
            f"/auth/realms/{args.realm}/protocol/openid-connect/token",
            200,
            data={
                "grant_type": "password",
                "client_id": args.client_id,
                "username": username,
                "password": password,
            },
        )
        if token_response is None:
            return
        access_token = token_response.json()["access_token"]
        headers = {"Authorization": f"Bearer {access_token}"}

        for iteration in range(args.iterations):
            await measured_request(client, samples, "profile", "GET", "/api/profile", 200)
            await measured_request(client, samples, "projects", "GET", "/api/projects", 200)
            await measured_request(
                client, samples, "me", "GET", "/api/me", 200, headers=headers
            )
            if args.contact_rate > 0 and random.random() < args.contact_rate:
                await measured_request(
                    client,
                    samples,
                    "contact",
                    "POST",
                    "/api/contact",
                    201,
                    json={
                        "name": f"Load User {number}",
                        "email": f"{username}@example.com",
                        "subject": f"Load test user {number} iteration {iteration}",
                        "message": "Generated by the controlled Personal Web load test.",
                    },
                )


def percentile(values: list[float], percent: float) -> float:
    if not values:
        return 0.0
    ordered = sorted(values)
    index = max(0, math.ceil(percent * len(ordered)) - 1)
    return ordered[index]


def report(samples: list[Sample], elapsed: float, args: argparse.Namespace) -> int:
    grouped: dict[str, list[Sample]] = defaultdict(list)
    for sample in samples:
        grouped[sample.endpoint].append(sample)

    print("\nPersonal Web load-test report")
    print("=" * 100)
    print(
        f"virtual_users={args.users} concurrency={args.concurrency} "
        f"ramp_up={args.ramp_up}s iterations={args.iterations} elapsed={elapsed:.2f}s"
    )
    print(f"{'endpoint':20} {'count':>8} {'errors':>8} {'avg ms':>10} {'p50':>10} {'p95':>10} {'p99':>10}")
    print("-" * 100)
    for endpoint, endpoint_samples in sorted(grouped.items()):
        latencies = [sample.elapsed_ms for sample in endpoint_samples]
        errors = sum(not sample.ok for sample in endpoint_samples)
        print(
            f"{endpoint:20} {len(endpoint_samples):8d} {errors:8d} "
            f"{statistics.fmean(latencies):10.1f} {percentile(latencies, 0.50):10.1f} "
            f"{percentile(latencies, 0.95):10.1f} {percentile(latencies, 0.99):10.1f}"
        )

    total = len(samples)
    errors = sum(not sample.ok for sample in samples)
    error_rate = errors / total if total else 1.0
    all_latencies = [sample.elapsed_ms for sample in samples]
    p95 = percentile(all_latencies, 0.95)
    rps = total / elapsed if elapsed else 0.0
    print("-" * 100)
    print(
        f"total_requests={total} errors={errors} error_rate={error_rate:.2%} "
        f"throughput={rps:.2f} req/s overall_p95={p95:.1f} ms"
    )
    failures = [sample for sample in samples if not sample.ok]
    for sample in failures[:20]:
        print(
            f"ERROR endpoint={sample.endpoint} status={sample.status} detail={sample.error}",
            file=sys.stderr,
        )

    passed = error_rate <= args.max_error_rate and p95 <= args.max_p95_ms
    print(
        "PASS" if passed else "FAIL",
        f"thresholds: error_rate <= {args.max_error_rate:.2%}, p95 <= {args.max_p95_ms:.0f} ms",
    )
    return 0 if passed else 2


async def async_main(args: argparse.Namespace) -> int:
    base_url = args.base_url.rstrip("/")
    if args.confirm_target.rstrip("/") != base_url:
        raise SystemExit("--confirm-target must exactly match --base-url")
    if args.users < 1 or args.concurrency < 1 or args.iterations < 1:
        raise SystemExit("users, concurrency and iterations must be positive")
    if not 0 <= args.contact_rate <= 1:
        raise SystemExit("--contact-rate must be between 0 and 1")

    password = secret_from_env(
        "LOADTEST_USER_PASSWORD", "Password shared by generated load users: "
    )
    limits = httpx.Limits(
        max_connections=args.concurrency,
        max_keepalive_connections=args.concurrency,
    )
    timeout = httpx.Timeout(args.timeout)
    samples: list[Sample] = []
    semaphore = asyncio.Semaphore(args.concurrency)
    started = time.perf_counter()
    async with httpx.AsyncClient(
        base_url=base_url,
        limits=limits,
        timeout=timeout,
        follow_redirects=False,
    ) as client:
        await asyncio.gather(
            *(
                virtual_user(number, args, password, client, semaphore, samples)
                for number in range(1, args.users + 1)
            )
        )
    elapsed = time.perf_counter() - started
    return report(samples, elapsed, args)


def main() -> int:
    args = parse_args()
    return asyncio.run(async_main(args))


if __name__ == "__main__":
    raise SystemExit(main())

